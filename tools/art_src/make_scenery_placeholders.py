def map_ground():
    w, h = 1280, 580
    img = Image.new("RGBA", (w, h), (126, 186, 96, 255))
    d = ImageDraw.Draw(img)
    r = random.Random(3)
    for i in range(220):  # grass tufts
        x, y = r.randint(0, w), r.randint(0, h)
        d.line([x, y, x - 4, y - 10], fill=(100, 160, 76, 255), width=3)
        d.line([x, y, x + 4, y - 10], fill=(100, 160, 76, 255), width=3)
    for band_top in (True, False):  # trees along the top and bottom edges
        for i in range(10):
            cx = r.randint(0, w)
            cy = r.randint(-10, 50) if band_top else r.randint(h - 50, h + 10)
            rad = r.randint(40, 70)
            for dx in (-w, 0, w):  # draw also shifted, so the tile wraps
                d.ellipse([cx + dx - rad, cy - rad, cx + dx + rad, cy + rad], fill=(62, 132, 64, 255), outline=OUTLINE, width=5)
    return img


