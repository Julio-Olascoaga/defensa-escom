def place_thumbnail(kind):
    s = 2
    size = 256 * s
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([8 * s, 8 * s, 248 * s, 248 * s], 40 * s, fill=(150, 205, 240, 255), outline=OUTLINE, width=8 * s)
    d.rectangle([12 * s, 180 * s, 244 * s, 230 * s], fill=(110, 180, 90, 255))
    d.rounded_rectangle([8 * s, 8 * s, 248 * s, 248 * s], 40 * s, outline=OUTLINE, width=8 * s)

    def box(x0, y0, x1, y1, fill):
        d.rectangle([x0 * s, y0 * s, x1 * s, y1 * s], fill=fill, outline=OUTLINE, width=5 * s)

    if kind == "escom":
        box(40, 90, 216, 190, CREAM)
        box(30, 76, 226, 96, GUINDA)
        for x in (56, 96, 140, 180):
            box(x, 110, x + 22, 140, (120, 170, 200, 255))
        box(116, 150, 140, 190, (70, 55, 60, 255))
        d.text((92 * s, 58 * s), "ESCOM", fill=OUTLINE, font_size=22 * s)
    elif kind == "biblioteca":
        box(36, 80, 220, 190, (188, 192, 198, 255))
        for x in range(48, 210, 28):
            box(x, 94, x + 18, 176, (90, 150, 205, 255))
        box(26, 66, 230, 84, (120, 124, 132, 255))
    elif kind == "estadio":
        d.ellipse([28 * s, 70 * s, 228 * s, 200 * s], fill=(200, 200, 205, 255), outline=OUTLINE, width=5 * s)
        d.ellipse([60 * s, 96 * s, 196 * s, 174 * s], fill=(96, 176, 80, 255), outline=OUTLINE, width=5 * s)
        d.line([128 * s, 96 * s, 128 * s, 174 * s], fill=(255, 255, 255, 255), width=3 * s)
    elif kind == "planetario":
        box(60, 140, 196, 190, CREAM)
        d.pieslice([60 * s, 60 * s, 196 * s, 220 * s], 180, 360, fill=(170, 176, 196, 255), outline=OUTLINE, width=5 * s)
        for x, y in ((40, 40), (210, 50), (190, 30)):
            d.ellipse([(x - 5) * s, (y - 5) * s, (x + 5) * s, (y + 5) * s], fill=GOLD)
    elif kind == "cenlex":
        box(50, 100, 206, 190, (230, 214, 180, 255))
        d.rounded_rectangle([30 * s, 34 * s, 120 * s, 80 * s], 14 * s, fill=(255, 255, 255, 255), outline=OUTLINE, width=4 * s)
        d.rounded_rectangle([130 * s, 46 * s, 226 * s, 92 * s], 14 * s, fill=(255, 255, 255, 255), outline=OUTLINE, width=4 * s)
        d.text((52 * s, 44 * s), "Hi!", fill=OUTLINE, font_size=24 * s)
        d.text((146 * s, 56 * s), "Hallo", fill=OUTLINE, font_size=20 * s)
    elif kind == "direccion":
        box(88, 40, 168, 190, (200, 196, 190, 255))
        for y in range(56, 176, 22):
            box(98, y, 158, y + 12, (110, 160, 200, 255))
        box(70, 170, 186, 190, GUINDA)
    elif kind == "cic":
        box(44, 110, 212, 190, (210, 214, 222, 255))
        d.line([170 * s, 110 * s, 190 * s, 50 * s], fill=OUTLINE, width=5 * s)
        d.pieslice([160 * s, 30 * s, 230 * s, 90 * s], 120, 300, fill=(230, 230, 236, 255), outline=OUTLINE, width=4 * s)
        for x in range(60, 160, 24):
            box(x, 128, x + 14, 150, (120, 220, 160, 255))
    elif kind == "auditorio":
        box(36, 70, 220, 190, (120, 30, 60, 255))
        box(70, 100, 186, 190, (60, 40, 50, 255))
        d.polygon([(100 * s, 120 * s), (156 * s, 120 * s), (128 * s, 104 * s)], fill=OUTLINE)  # mortarboard
        box(110, 120, 146, 132, OUTLINE)
        d.line([146 * s, 120 * s, 156 * s, 150 * s], fill=GOLD, width=4 * s)
    return img.resize((256, 256), Image.LANCZOS)


