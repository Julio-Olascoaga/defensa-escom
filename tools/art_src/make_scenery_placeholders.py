def cloud_shadow():
    img = Image.new("RGBA", (720, 420), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    r = random.Random(5)
    for i in range(9):
        cx, cy = r.randint(180, 540), r.randint(150, 270)
        rad = r.randint(90, 150)
        d.ellipse([cx - rad, cy - rad * 0.7, cx + rad, cy + rad * 0.7], fill=(20, 20, 40, 255))
    img = img.filter(ImageFilter.GaussianBlur(40))
    return img


def glow():
    size = 160
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = img.load()
    for y in range(size):
        for x in range(size):
            dist = math.hypot(x - size / 2, y - size / 2) / (size / 2)
            a = max(0.0, 1.0 - dist) ** 1.8
            px[x, y] = (255, 214, 140, int(255 * a))
    return img


