"""Placeholder art for Block 11 (v1.5): the scenery of the worlds.

Draws, with simple flat shapes, everything the scenery needs until the final
art arrives (generated by the team and dropped in the same paths):
    (the first placeholder backgrounds, replaced by compose_backgrounds.py)
    art/scenery/*.png                    pigeon, leaf, paper, cloud shadow, glow, foreground branch
    art/map/map_ground.png               tile of the illustrated career map
    art/map/place_1.png ... place_8.png  thumbnail of the place of each semester

Composition of a background (as in the 1.0, aligned with the board):
    left   0..160 px     the building (the student's safe zone)
    top    0..220 px     garden strip (behind the top bar)
    centre 160..2320 px  the floor of the 5 lanes (y 220..1420)
    right  2320..2560 px where the enemies come in

Usage (from the project root, Pillow installed):
    python tools/art_src/make_scenery_placeholders.py
"""

import math
import os
import random

from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUTLINE = (43, 27, 46, 255)
GUINDA = (108, 29, 69, 255)
GOLD = (242, 179, 61, 255)
CREAM = (244, 236, 216, 255)
W, H = 2560, 1440
BOARD = (160, 220, 2320, 1420)

rnd = random.Random(11)


def path(*parts):
    p = os.path.join(ROOT, *parts)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    return p


def shade(color, f):
    return tuple(max(0, min(255, int(c * f))) for c in color[:3]) + (255,)


def jitter(color, amount):
    d = rnd.randint(-amount, amount)
    return tuple(max(0, min(255, c + d)) for c in color[:3]) + (255,)


