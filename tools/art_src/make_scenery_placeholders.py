def draw_pavers(d, box, size, base, grout, amount=8, offset_rows=True):
    x0, y0, x1, y1 = box
    row = 0
    y = y0
    while y < y1:
        shift = size // 2 if (offset_rows and row % 2) else 0
        x = x0 - shift
        while x < x1:
            d.rectangle([x, y, x + size, y + size], fill=jitter(base, amount), outline=grout, width=4)
            x += size
        y += size
        row += 1


def draw_garden_strip(d, y_bottom, tree_colors, seed):
    r = random.Random(seed)
    d.rectangle([0, 0, W, y_bottom], fill=(88, 150, 70, 255))
    # hedges along the bottom of the strip
    x = 140
    while x < W - 120:
        w = r.randint(220, 340)
        d.rounded_rectangle([x, y_bottom - 110, x + w, y_bottom - 10], 45, fill=(58, 120, 52, 255), outline=OUTLINE, width=6)
        for k in range(5):
            cx = x + r.randint(30, w - 30)
            d.ellipse([cx - 22, y_bottom - 100, cx + 22, y_bottom - 60], fill=(78, 145, 64, 255))
        x += w + r.randint(30, 60)
    # tree tops
    for i in range(12):
        cx = r.randint(150, W - 150)
        cy = r.randint(10, y_bottom - 120)
        rad = r.randint(60, 95)
        col = r.choice(tree_colors)
        d.ellipse([cx - rad, cy - rad, cx + rad, cy + rad], fill=col, outline=OUTLINE, width=6)
        d.ellipse([cx - rad * 0.5, cy - rad * 0.6, cx + rad * 0.1, cy - rad * 0.1], fill=shade(col, 1.15))
    # kerb between the garden and the floor
    d.rectangle([0, y_bottom - 8, W, y_bottom + 6], fill=(150, 145, 140, 255), outline=OUTLINE, width=4)


def draw_building_left(d, roof, wall, window, sign_text_color, glass=False):
    # roof seen from above
    d.rectangle([0, 0, 112, H], fill=roof, outline=OUTLINE, width=6)
    for y in range(40, H, 90):
        d.line([10, y, 100, y], fill=shade(roof, 0.85), width=6)
    # facade wall facing the explanada
    d.rectangle([108, 0, 160, H], fill=wall, outline=OUTLINE, width=6)
    for y in range(60, H - 60, 150):
        if 760 <= y <= 900:
            continue
        if glass:
            d.rectangle([116, y, 152, y + 120], fill=window, outline=OUTLINE, width=4)
            d.line([122, y + 10, 140, y + 50], fill=(220, 240, 255, 255), width=4)
        else:
            d.rectangle([118, y + 10, 150, y + 90], fill=window, outline=OUTLINE, width=4)
            d.line([134, y + 10, 134, y + 90], fill=OUTLINE, width=3)
    # main entrance in the middle lane
    d.rectangle([104, 740, 172, 960], fill=shade(wall, 0.8), outline=OUTLINE, width=6)
    d.rectangle([118, 770, 158, 930], fill=(70, 55, 60, 255), outline=OUTLINE, width=4)
    d.rectangle([0, 700, 112, 1000], fill=shade(roof, 0.8), outline=OUTLINE, width=6)  # canopy
    # sign on the roof
    for i, ch in enumerate(sign_text_color[0]):
        cy = 330 + i * 70
        d.rounded_rectangle([20, cy - 28, 92, cy + 28], 10, fill=GOLD, outline=OUTLINE, width=4)
        d.text((44, cy - 20), ch, fill=OUTLINE, font_size=40)


def draw_entry_right(d, floor, fence):
    d.rectangle([2320, 0, W, H], fill=floor)
    draw_pavers(d, (2320, 220, W, H), 120, floor, shade(floor, 0.78), 6, False)
    d.line([2322, 220, 2322, H], fill=OUTLINE, width=6)
    # open fence (reja) on the far right: the enemies come through it
    for y in list(range(240, 600, 60)) + list(range(1040, 1420, 60)):
        d.line([2500, y, 2500, y + 40], fill=fence, width=12)
    d.line([2500, 230, 2500, 600], fill=OUTLINE, width=3)
    d.line([2500, 1040, 2500, 1420], fill=OUTLINE, width=3)
    d.rectangle([2484, 590, 2516, 640], fill=shade(fence, 0.8), outline=OUTLINE, width=4)
    d.rectangle([2484, 1000, 2516, 1050], fill=shade(fence, 0.8), outline=OUTLINE, width=4)


def finish(img, name):
    img = img.convert("RGB").filter(ImageFilter.SMOOTH)
    img.save(path("art", "backgrounds", name), quality=90)


def background_escom():
    img = Image.new("RGBA", (W, H), (190, 182, 168, 255))
    d = ImageDraw.Draw(img)
    # explanada: warm grey pavers with a guinda border band every lane
    draw_pavers(d, BOARD, 80, (196, 188, 172, 255), (160, 150, 138, 255), 7)
    for lane in range(6):
        y = 220 + lane * 240
        d.rectangle([160, y - 6, 2320, y + 6], fill=(150, 92, 98, 255))
    draw_entry_right(d, (176, 176, 172, 255), GUINDA)
    draw_garden_strip(d, 220, [(60, 130, 60, 255), (72, 140, 58, 255), (50, 112, 62, 255)], 1)
    draw_building_left(d, GUINDA, CREAM, (120, 170, 200, 255), ("ESCOM",))
    finish(img, "escom_bg.jpg")


def background_biblioteca():
    img = Image.new("RGBA", (W, H), (214, 210, 200, 255))
    d = ImageDraw.Draw(img)
    # plaza of big pale stone slabs
    draw_pavers(d, BOARD, 120, (222, 216, 204, 255), (176, 168, 156, 255), 6)
    for i in range(0, 2400, 240):  # brick bands across the plaza
        d.rectangle([160 + i, 220, 160 + i + 20, 1420], fill=(176, 108, 84, 255))
    draw_entry_right(d, (196, 196, 190, 255), (70, 90, 110, 255))
    draw_garden_strip(d, 220, [(64, 128, 70, 255), (84, 150, 72, 255), (58, 118, 82, 255)], 2)
    draw_building_left(d, (120, 124, 132, 255), (188, 192, 198, 255), (90, 150, 205, 255), ("BIBLIO",), glass=True)
    finish(img, "biblioteca_bg.jpg")


