def pigeon(flying):
    s = 4  # drawn 4x bigger and reduced: smooth edges
    img = Image.new("RGBA", (96 * s, 80 * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    body = (150, 156, 170, 255)
    # tail, body, head (looking left)
    d.polygon([(70 * s, 46 * s), (92 * s, 38 * s), (92 * s, 58 * s)], fill=shade(body, 0.8), outline=OUTLINE, width=3 * s)
    d.ellipse([22 * s, 30 * s, 78 * s, 64 * s], fill=body, outline=OUTLINE, width=3 * s)
    d.ellipse([10 * s, 18 * s, 38 * s, 44 * s], fill=(120, 128, 146, 255), outline=OUTLINE, width=3 * s)
    d.ellipse([20 * s, 34 * s, 34 * s, 46 * s], fill=(110, 170, 140, 255))  # green neck shine
    d.polygon([(4 * s, 30 * s), (12 * s, 27 * s), (12 * s, 33 * s)], fill=(230, 160, 80, 255), outline=OUTLINE)
    d.ellipse([17 * s, 25 * s, 23 * s, 31 * s], fill=(240, 120, 60, 255))
    if flying:
        d.polygon([(36 * s, 40 * s), (60 * s, 2 * s), (70 * s, 40 * s)], fill=(190, 196, 210, 255), outline=OUTLINE, width=3 * s)
    else:
        d.ellipse([38 * s, 36 * s, 72 * s, 56 * s], fill=shade(body, 0.85), outline=OUTLINE, width=2 * s)
        for fx in (40, 52):
            d.line([fx * s, 62 * s, fx * s, 74 * s], fill=(230, 120, 90, 255), width=3 * s)
    return img.resize((96, 80), Image.LANCZOS)


